// Drift caught here: the public API changing without anybody deciding it
// should.
//
// A compiler cannot catch this. Renaming an exported field, widening a
// parameter, adding a method to an interface somebody else implements — all of
// them compile perfectly inside this module and break every caller outside it.
// The only way to make such a change visible is to write the whole surface down
// and diff it, so that "we shipped a breaking change" is a line in a pull
// request that a human had to approve rather than a discovery made by a user.
//
// api/ovrin.txt is that record, in the format Go uses for its own api/go1.N.txt.
// Two properties are deliberate:
//
//   - Parameter names are dropped. Renaming a parameter is a documentation
//     change, not an API change, and a golden file that churns on cosmetics is
//     a golden file people stop reading. docs_mirror_test.go checks parameter
//     names, where they matter, against the docs that show them.
//   - Lines are sorted globally. Moving a type from one file to another
//     produces a zero-line diff, so the file records the API rather than the
//     file layout.
//
// The surface is read with go/ast rather than reflection or go/types: the test
// must be hermetic and fast, and reflection cannot see an interface's method
// set on a type nobody implements, nor a constant's declared type at all.
//
// This file also holds the two helpers the other two drift tests share —
// parseRootPackage and render — because all three read the same package the
// same way and three copies of that would be its own drift risk.
//
// The tests are in package ovrin rather than ovrin_test: defaults_doc_test.go
// needs to name the Default* constants as the code names them, so that the
// compiler is one of the three things checking the bridge map. Nothing here
// touches unexported state — the package is parsed as source, not reflected on.
package ovrin

import (
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"regexp"
	"sort"
	"strings"
	"testing"
)

// apiPath is the golden file, relative to the package directory.
const apiPath = "api/ovrin.txt"

// defaultAPIHeader is written only when api/ovrin.txt does not exist. An
// existing file keeps its own header verbatim: the prose there is somebody's
// decision, not this generator's output.
const defaultAPIHeader = `# ovrin public API surface.
#
# One line per exported symbol, struct field and interface method, sorted.
# Generated by ` + "`go test -run TestAPI -update .`" + `; committed so that any change
# to the public API is a visible line in a diff that somebody had to intend.
#
`

var updateAPI = flag.Bool("update", false, "rewrite "+apiPath+" from the source")

func TestAPI(t *testing.T) {
	t.Parallel()

	_, files := parseRootPackage(t)
	got := apiSurface(t, files)

	if *updateAPI {
		writeAPI(t, got)
		t.Logf("wrote %d lines to %s", len(got), apiPath)
		return
	}

	want := readAPI(t)
	added, removed := diffLines(want, got)
	if len(added) == 0 && len(removed) == 0 {
		return
	}

	var b strings.Builder
	fmt.Fprintf(&b, "the public API does not match %s (%d added, %d removed)\n\n",
		apiPath, len(added), len(removed))
	for _, l := range removed {
		fmt.Fprintf(&b, "  - %s\n", l)
	}
	for _, l := range added {
		fmt.Fprintf(&b, "  + %s\n", l)
	}
	b.WriteString("\n(- is in " + apiPath + " but not in the code; + is in the code but not in " + apiPath + ")\n")
	b.WriteString("\nIf this change was intentional, re-run with -update, update the docs,\n")
	b.WriteString("and add a CHANGELOG entry:\n\n")
	b.WriteString("    go test -run TestAPI -update .\n")
	t.Error(b.String())
}


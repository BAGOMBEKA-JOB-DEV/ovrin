func readAPI(t *testing.T) []string {
	t.Helper()
	b, err := os.ReadFile(apiPath)
	if err != nil {
		t.Fatalf("reading %s: %v (re-run with -update to create it)", apiPath, err)
	}
	var out []string
	for _, line := range strings.Split(string(b), "\n") {
		line = strings.TrimRight(line, "\r")
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		out = append(out, line)
	}
	sort.Strings(out)
	return out
}

func writeAPI(t *testing.T, lines []string) {
	t.Helper()

	header := defaultAPIHeader
	if b, err := os.ReadFile(apiPath); err == nil {
		// Keep whatever header the file already carries: the prose there was
		// written deliberately and is not this generator's to rewrite.
		var kept []string
		for _, line := range strings.Split(string(b), "\n") {
			if line != "" && !strings.HasPrefix(line, "#") {
				break
			}
			kept = append(kept, line)
		}
		if len(kept) > 0 {
			header = strings.Join(kept, "\n") + "\n"
		}
	}

	var out strings.Builder
	out.WriteString(header)
	for _, l := range lines {
		out.WriteString(l)
		out.WriteByte('\n')
	}
	if err := os.WriteFile(apiPath, []byte(out.String()), 0o644); err != nil {
		t.Fatalf("writing %s: %v", apiPath, err)
	}
}

// diffLines reports what is in got but not want, and what is in want but not
// got. Both inputs are sorted.
func diffLines(want, got []string) (added, removed []string) {
	inWant := make(map[string]bool, len(want))
	for _, l := range want {
		inWant[l] = true
	}
	inGot := make(map[string]bool, len(got))
	for _, l := range got {
		inGot[l] = true
	}
	for _, l := range got {
		if !inWant[l] {
			added = append(added, l)
		}
	}
	for _, l := range want {
		if !inGot[l] {
			removed = append(removed, l)
		}
	}
	return added, removed
}

const (
	scale   = 3  // pixels per font pixel
	padding = 24 // page margin
	leading = 6  // blank rows between lines
	advance = 6  // font pixels per character, including the gap
)

func main() {
	lines := []string{
		"KAMPALA SUPPLIES LTD",
		"PLOT 14 NAKAWA ROAD",
		"TIN 1002938475",
		"",
		"*** SALES RECEIPT ***",
		"",
		"RECEIPT NO: INV-2026-0417",
		"DATE: 14/03/2026",
		"",
		"A4 PAPER 80GSM   40   12,500",
		"TONER CARTRIDGE   4  185,000",
		"",
		"SUBTOTAL         UGX 1,240,000",
		"VAT 18 PCT       UGX   223,200",
		"TOTAL            UGX 1,463,200",
		"",
		"PAID BY: CASH",
		"THANK YOU",
	}

	// Size the page to its content. A fixed width silently clipped the
	// receipt number and every amount — the fields this example exists to
	// extract — and a fixture that is missing what it is meant to demonstrate
	// is worse than no fixture.
	longest := 0
	for _, line := range lines {
		if n := len([]rune(line)); n > longest {
			longest = n
		}
	}
	lineHeight := 7*scale + leading
	width := padding*2 + longest*advance*scale
	height := padding*2 + lineHeight*len(lines)
	m := image.NewRGBA(image.Rect(0, 0, width, height))

	// Receipts are dark on light. Anything else would be testing the model's
	// tolerance for unusual documents rather than ovrin's pipeline.
	for y := 0; y < height; y++ {
		for x := 0; x < width; x++ {
			m.Set(x, y, color.RGBA{R: 250, G: 249, B: 245, A: 255})
		}
	}
	ink := color.RGBA{R: 24, G: 24, B: 28, A: 255}

	for i, line := range lines {
		draw(m, strings.ToUpper(line), padding, padding+i*lineHeight, ink)
	}

	f, err := os.Create("examples/receipt/receipt.png")
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()
	if err := png.Encode(f, m); err != nil {
		log.Fatal(err)
	}
	log.Printf("wrote examples/receipt/receipt.png (%dx%d)", width, height)
}

func draw(m *image.RGBA, s string, x, y int, c color.Color) {
	for _, r := range s {
		g, ok := glyphs[r]
		if !ok {
			g = glyphs[' ']
		}
		for row := 0; row < 7; row++ {
			for col := 0; col < 5; col++ {
				if g[row]&(1<<(4-col)) == 0 {
					continue
				}
				for dy := 0; dy < scale; dy++ {
					for dx := 0; dx < scale; dx++ {
						m.Set(x+col*scale+dx, y+row*scale+dy, c)
					}
				}
			}
		}
		x += advance * scale
	}
}

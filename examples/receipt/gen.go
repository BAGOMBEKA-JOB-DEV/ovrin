// Command gen draws the synthetic receipt this example extracts from.
//
// It exists so the fixture is reproducible and so nobody is tempted to commit
// a real receipt: rule §7.6 forbids real personal data in the repository, and a
// receipt is somebody's shopping. Everything on it is invented.
//
// The font is a hand-rolled 5x7 bitmap rather than a dependency, because this
// repository has none and a fixture generator is not the place to start.
//
//	go run examples/receipt/gen.go
